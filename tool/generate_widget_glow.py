#!/usr/bin/env python3
"""Generates the Neon glow variants of the widget's session timer (D62).

Widgets cannot set a text shadow at run time, so the layout holds one
session Chronometer per glow colour (GONE), and the provider shows the one
named by the Dart side (`<accent>_<light|dark>`). The colours are the app's
Neon primary colours; test/services/widget/widget_glow_test.dart fails when
they drift from the theme, then update PRIMARY and run this again.

Writes, relative to the project root:
- the variants into res/layout/switcher_widget.xml, between the markers;
- res/values/widget_timer_styles.xml (the shared session style);
- SwitcherGlowViews.kt, the variants' view ids for the provider.

Run after changing accents or the theme:  python3 tool/generate_widget_glow.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
KOTLIN = (
    ROOT
    / "android/app/src/main/kotlin/io/github/puzzle4286svg/lifestring"
    / "SwitcherGlowViews.kt"
)

# Neon primary colour per accent: (light, dark); Black uses dark's.
PRIMARY = {
    "teal": ("006b5f", "82d5c7"),
    "blue": ("39608f", "a3c9fe"),
    "violet": ("69548d", "d4bbfc"),
    "amber": ("835414", "f9ba72"),
    "rose": ("8e4958", "ffb2bf"),
    "indigo": ("525a92", "bbc3ff"),
    "cyan": ("006876", "82d3e2"),
    "green": ("3b6939", "a1d39a"),
    "lime": ("626118", "cccb76"),
    "orange": ("8f4c38", "ffb5a0"),
    "red": ("904a44", "ffb4ac"),
    "pink": ("8d4a5a", "ffb1c2"),
    "brown": ("8f4c34", "ffb59c"),
    "slate": ("0e6681", "8ad0ee"),
}

# Like Neon.textGlowFor's tight layer (alpha 0.8, blur 8 at 45 sp), scaled
# to the widget's 15 sp. In px: TextView shadows take no units.
GLOW_ALPHA = "CC"
GLOW_RADIUS_PX = 9

BEGIN = "<!-- glow variants: generated by tool/generate_widget_glow.py -->"
END = "<!-- end of glow variants -->"
INDENT = " " * 12


def variants():
    for accent, (light, dark) in PRIMARY.items():
        for brightness, rgb in (("light", light), ("dark", dark)):
            yield f"{accent}_{brightness}", rgb


def main():
    layout = RES / "layout/switcher_widget.xml"
    text = layout.read_text()
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    views = "".join(
        f'\n{INDENT}<Chronometer\n'
        f'{INDENT}    android:id="@+id/timer_session_{name}"\n'
        f'{INDENT}    style="@style/WidgetTimerSession"\n'
        f'{INDENT}    android:shadowColor="#{GLOW_ALPHA}{rgb}"\n'
        f'{INDENT}    android:shadowRadius="{GLOW_RADIUS_PX}"\n'
        f'{INDENT}    android:visibility="gone" />'
        for name, rgb in variants()
    )
    layout.write_text(f"{head}{BEGIN}{views}\n{INDENT}{END}{tail}")

    (RES / "values/widget_timer_styles.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/generate_widget_glow.py (D62). -->\n"
        "<resources>\n"
        '    <style name="WidgetTimerSession">\n'
        '        <item name="android:layout_width">wrap_content</item>\n'
        '        <item name="android:layout_height">wrap_content</item>\n'
        '        <item name="android:fontFamily">sans-serif-medium</item>\n'
        '        <item name="android:fontFeatureSettings">tnum</item>\n'
        '        <item name="android:textSize">15sp</item>\n'
        "    </style>\n"
        "</resources>\n"
    )

    entries = "".join(
        f'    "{name}" to R.id.timer_session_{name},\n' for name, _ in variants()
    )
    KOTLIN.write_text(
        "// Generated by tool/generate_widget_glow.py (D62). Do not edit.\n"
        "package io.github.puzzle4286svg.lifestring\n\n"
        "/** The glowing session views by variant (`<accent>_<light|dark>`). */\n"
        f"val glowSessionViews: Map<String, Int> = mapOf(\n{entries})\n"
    )


if __name__ == "__main__":
    main()
