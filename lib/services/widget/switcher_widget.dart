/// The home-screen task switcher (D49): the eight grid tiles, optionally
/// with a timer above them (D62). Tapping a tile switches to it without
/// opening the app.
///
/// Each tile is drawn here as a PNG (same look as in the app, Neon
/// included) and handed to the Android provider `SwitcherWidgetProvider`
/// through home_widget's storage, together with the activity id. A tap
/// sends `timetracker://switch?id=<id>` to [onSwitcherTap], which runs in
/// a background Dart isolate and uses the normal [TrackingService.switchTo].
abstract final class SwitcherWidget {
  static const androidProvider =
      'io.github.puzzle4286svg.lifestring.SwitcherWidgetProvider';

  /// Logical size of one tile image, including [padding] on every side.
  ///
  /// The shape of one slot when the widget is 4 x 1 cells (about 71 x 37 dp
  /// on the developer's phone), so the tiles fill the frame.
  static const tileSize = Size(100, 52);

  /// [tileSize] with the timer row on (D62): as wide, but flatter, so the
  /// tiles still fill the width of a 4 x 1 cell widget. Two 37 dp rows less
  /// the 20 dp timer row leave about 27 dp per row.
  static const timerTileSize = Size(100, 38);

  /// Gap around the tile; the Neon glow must fade out inside it, anything
  /// beyond would be cut off in a hard square.
  static const padding = 4.0;

  // Shown about 71 dp wide (about 213 px on a 3x screen).
  static const pixelRatio = 2.5;

  static String idKey(int position) => 'slot_${position}_id';
  static String imageKey(int position) => 'slot_${position}_image';

  /// Timer row (D62). Times are milliseconds since the epoch, as strings;
  /// the provider turns them into self-ticking Chronometers.
  static const timerShownKey = 'timer_shown';
  static const timerSessionStartKey = 'timer_session_start';
  static const timerClosedTodayKey = 'timer_closed_today';
  static const timerDayEndKey = 'timer_day_end';

  /// Timer colours as ARGB integers, like the app's header: the session in
  /// the primary colour, today's total in onSurfaceVariant.
  static const timerSessionColorKey = 'timer_session_color';
  static const timerTotalColorKey = 'timer_total_color';

  /// Neon only: which glowing session view to show, see [timerGlow].
  static const timerGlowKey = 'timer_glow';

  /// The Neon glow variant for [accent] and [appearance]:
  /// `<accent>_<light|dark>`, the suffix of a `timer_session_…` view
  /// generated by tool/generate_widget_glow.py (Black glows like Dark).
  static String timerGlow(AccentPalette accent, AppearanceMode appearance) =>
      '${accent.name}_${appearance == AppearanceMode.light ? 'light' : 'dark'}';

  /// Registers the tap handler; call once at app start (Android only).
  static Future<void> register() =>
      HomeWidget.registerInteractivityCallback(onSwitcherTap);

  /// Redraws the widget from the database. Errors are swallowed: the widget
  /// is a convenience and must never break the app.
  static Future<void> sync(DatabaseExecutor db) async {
    if (!Platform.isAndroid) return;
    try {
      final state = await SwitcherState.load(db);
      final scheme = state.colorScheme;
      for (var position = 1; position <= 8; position++) {
        final activity = state.at(position);
        final png = await renderTile(
          activity,
          size: state.timer != null ? timerTileSize : tileSize,
          active: activity != null && activity.id == state.activeId,
          scheme: scheme,
          neon: state.style == AppStyle.neon,
          filter: styleFilter(state.style),
        );
        await HomeWidget.saveFile(imageKey(position), png, extension: 'png');
        // No id: an empty slot, which opens the app to set it up.
        await HomeWidget.saveWidgetData<String>(
          idKey(position),
          activity == null ? null : '${activity.id}',
        );
      }
      await HomeWidget.saveWidgetData<String>(
        timerShownKey,
        '${state.timer != null}',
      );
      if (state.timer case final timer?) {
        await HomeWidget.saveWidgetData<String>(
          timerSessionColorKey,
          '${scheme.primary.toARGB32()}',
        );
        await HomeWidget.saveWidgetData<String>(
          timerTotalColorKey,
          '${scheme.onSurfaceVariant.toARGB32()}',
        );
        await HomeWidget.saveWidgetData<String>(
          timerGlowKey,
          state.style == AppStyle.neon
              ? timerGlow(state.accent, state.appearance)
              : null,
        );
        await HomeWidget.saveWidgetData<String>(
          timerSessionStartKey,
          '${timer.sessionStart.millisecondsSinceEpoch}',
        );
        await HomeWidget.saveWidgetData<String>(
          timerClosedTodayKey,
          '${timer.closedToday.inMilliseconds}',
        );
        await HomeWidget.saveWidgetData<String>(
          timerDayEndKey,
          '${timer.dayEnd.millisecondsSinceEpoch}',
        );
      }
      await HomeWidget.updateWidget(qualifiedAndroidName: androidProvider);
    } on Object catch (e) {
      debugPrint('Switcher widget update failed: $e');
    }
  }

  /// One tile as PNG bytes, drawn like [ActivityTile]; [activity] is null
  /// for an empty slot ("+").
  static Future<Uint8List> renderTile(
    Activity? activity, {
    required bool active,
    required ColorScheme scheme,
    required bool neon,
    ColorFilter? filter,
    Size size = tileSize,
  }) async {
    final recorder = ui.PictureRecorder();
    final canvas = Canvas(recorder)..scale(pixelRatio);
    // Like the app in Grayscale (D59).
    if (filter != null) {
      canvas.saveLayer(Offset.zero & size, Paint()..colorFilter = filter);
    }
    paintTile(
      canvas,
      activity,
      active: active,
      scheme: scheme,
      neon: neon,
      size: size,
    );
    if (filter != null) canvas.restore();
    final image = await recorder.endRecording().toImage(
      (size.width * pixelRatio).round(),
      (size.height * pixelRatio).round(),
    );
    final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
    image.dispose();
    return bytes!.buffer.asUint8List();
  }

  /// Paints one tile into a [size] area (logical pixels). Icons and
  /// letters scale with the height, so flatter tiles keep their margins.
  static void paintTile(
    Canvas canvas,
    Activity? activity, {
    required bool active,
    required ColorScheme scheme,
    required bool neon,
    Size size = tileSize,
  }) {
    const radius = Radius.circular(11);
    final rect = Offset.zero & size;
    final tile = RRect.fromRectAndRadius(rect.deflate(padding), radius);
    final scale = size.height / tileSize.height;
    if (activity == null) {
      paintEmptyTile(canvas, tile, scheme, scale: scale);
      return;
    }
    final color = Color(activity.color);

    if (active && neon) {
      // Tighter than the app's two-layer glow (Neon.boxGlowFor), so it fits
      // in [padding]: sigma 1.4 fades out within about 4 px.
      canvas.drawRRect(
        tile.inflate(0.5),
        Paint()
          ..color = color.withValues(alpha: 0.85)
          ..maskFilter = const MaskFilter.blur(BlurStyle.normal, 1.4),
      );
    }
    canvas.drawRRect(
      tile,
      Paint()
        ..color = ActivityTile.fillFor(scheme, activity, active, neon: neon),
    );
    if (active) {
      canvas.drawRRect(
        tile.deflate(1.5),
        Paint()
          ..style = PaintingStyle.stroke
          ..strokeWidth = 3
          ..color = scheme.onSurface,
      );
    } else if (neon) {
      canvas.drawRRect(
        tile.deflate(0.75),
        Paint()
          ..style = PaintingStyle.stroke
          ..strokeWidth = 1.5
          ..color = color.withValues(alpha: 0.6),
      );
    }

    final foreground = ActivityTile.foregroundFor(
      scheme,
      activity,
      active,
      neon: neon,
    );
    final icon = activityIcon(activity.icon);
    final label = TextPainter(
      textDirection: TextDirection.ltr,
      text: icon != null
          ? TextSpan(
              text: String.fromCharCode(icon.codePoint),
              style: TextStyle(
                fontFamily: icon.fontFamily,
                package: icon.fontPackage,
                // Larger than in the app: the widget tiles are smaller.
                fontSize: (active ? 32 : 30) * scale,
                color: foreground,
              ),
            )
          : TextSpan(
              text: activity.name.characters.first.toUpperCase(),
              style: TextStyle(
                fontSize: 27 * scale,
                fontWeight: FontWeight.w600,
                color: foreground,
              ),
            ),
    )..layout();
    label.paint(
      canvas,
      rect.center - Offset(label.width / 2, label.height / 2),
    );
    label.dispose();
  }
}

/// An empty slot like in the app: an outline and "+", no fill.
void paintEmptyTile(
  Canvas canvas,
  RRect tile,
  ColorScheme scheme, {
  double scale = 1,
}) {
  canvas.drawRRect(
    tile.deflate(0.5),
    Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1
      ..color = scheme.outlineVariant,
  );
  final plus = TextPainter(
    textDirection: TextDirection.ltr,
    text: TextSpan(
      text: String.fromCharCode(Icons.add.codePoint),
      style: TextStyle(
        fontFamily: Icons.add.fontFamily,
        package: Icons.add.fontPackage,
        fontSize: 30 * scale,
        color: ActivityTile.foregroundFor(scheme, null, false),
      ),
    ),
  )..layout();
  plus.paint(canvas, tile.center - Offset(plus.width / 2, plus.height / 2));
  plus.dispose();
}

/// What the widget's timer row counts from (D62).
class SwitcherTimer {
  const SwitcherTimer({
    required this.sessionStart,
    required this.closedToday,
    required this.dayEnd,
  });

  /// Start of the open entry: the session timer counts up from here.
  final DateTime sessionStart;

  /// Today's time on the running activity from closed entries; today's
  /// total is this plus the session.
  final Duration closedToday;

  /// When the session's day ends and both timers start again from zero.
  final DateTime dayEnd;
}

/// What the widget shows, read straight from the database.
class SwitcherState {
  SwitcherState._(
    this._byPosition,
    this.activeId,
    this.colorScheme,
    this.style,
    this.timer,
    this.accent,
    this.appearance,
  );

  final Map<int, Activity> _byPosition;
  final int? activeId;
  final ColorScheme colorScheme;
  final AppStyle style;

  /// Null when the timer row is turned off or nothing is tracked.
  final SwitcherTimer? timer;

  final AccentPalette accent;
  final AppearanceMode appearance;

  Activity? at(int position) => _byPosition[position];

  static Future<SwitcherState> load(DatabaseExecutor db) async {
    final settings = await SettingsRepository(db).load();
    final activities = await ActivityRepository(db).liveActivities();
    final entries = TimeEntryRepository(db);
    final open = await entries.openEntry();
    SwitcherTimer? timer;
    if (settings.widgetTimer && open != null) {
      final today = localDay(open.start);
      final todays = await entries.overlapping(today.start, today.end);
      timer = SwitcherTimer(
        sessionStart: open.start,
        closedToday: trackedInRange(
          todays.where((e) => !e.isOpen),
          today,
          open.start,
          activityId: open.activityId,
        ),
        dayEnd: today.end,
      );
    }
    return SwitcherState._(
      {for (final a in activities) a.position!: a},
      open?.activityId,
      buildTheme(
        settings.appearance,
        settings.accent,
        style: settings.style,
      ).colorScheme,
      settings.style,
      timer,
      settings.accent,
      settings.appearance,
    );
  }
}

/// The activity id in a tile's `timetracker://switch?id=<id>` link, or null
/// for anything else.
int? switchTargetId(Uri? uri) {
  if (uri == null || uri.scheme != 'timetracker' || uri.host != 'switch') {
    return null;
  }
  return int.tryParse(uri.queryParameters['id'] ?? '');
}

/// Runs in a background isolate when a widget tile is tapped.
@pragma('vm:entry-point')
Future<void> onSwitcherTap(Uri? uri) async {
  final id = switchTargetId(uri);
  if (id == null) return;
  // Own connection: sqflite shares single instances per path across the
  // whole process, so closing a shared one would close the app's database
  // if it is open at the same time.
  final db = await openAppDatabase(
    databaseFactory,
    p.join(await getDatabasesPath(), databaseFileName),
    singleInstance: false,
  );
  try {
    final tracking = TrackingService(db, const SystemClock());
    await tracking.reconcile();
    await tracking.switchTo(id);
    await SwitcherWidget.sync(db);
  } on Object catch (e) {
    // E.g. the activity was deleted since the widget was drawn: redraw.
    debugPrint('Switcher widget tap failed: $e');
    await SwitcherWidget.sync(db);
  } finally {
    await db.close();
  }
}
